/**
 * Client-side ASS string generator matching ass_compiler.py specification
 */
function compileAssClient(specs: CaptionSpec[], width: number = 1920, height: number = 1080): string {
  const hexToAssBgr = (hex: string, alphaHex: string = '00') => {
    const clean = hex.replace('#', '');
    if (clean.length !== 6) return `&H${alphaHex}F7C34F&`;
    const r = clean.substring(0, 2);
    const g = clean.substring(2, 4);
    const b = clean.substring(4, 6);
    return `&H${alphaHex}${b.toUpperCase()}${g.toUpperCase()}${r.toUpperCase()}&`;
  };

  const msToAssTimestamp = (ms: number): string => {
    const totalCs = Math.floor(Math.max(0, ms) / 10);
    const cs = totalCs % 100;
    const totalSec = Math.floor(totalCs / 100);
    const s = totalSec % 60;
    const totalMin = Math.floor(totalSec / 60);
    const m = totalMin % 60;
    const h = Math.floor(totalMin / 60);
    return `${h}:${String(m).padStart(2, '0')}:${String(s).padStart(2, '0')}.${String(cs).padStart(2, '0')}`;
  };

  const baselineFontPx = Math.round(height * 0.05);
  const marginVPx = Math.round(height * 0.06);
  const readAheadAss = hexToAssBgr('#B0B5BC', '00');

  let ass = `[Script Info]
; Script generated by Automated Caption with Intention (CwiRenderer v2.0-cwi)
Title: Caption with Intention Expressive Subtitles
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: ${width}
PlayResY: ${height}

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: CWI_Default,Roboto Flex,${baselineFontPx},&H00F7C34F&,${readAheadAss},&H1A000000&,&H1A000000&,400,0,0,0,100,100,0,0,3,16,0,2,80,80,${marginVPx},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
`;

  for (const spec of specs) {
    for (const ev of spec.non_speech_events || []) {
      const sTs = msToAssTimestamp(ev.start_ms);
      const eTs = msToAssTimestamp(ev.end_ms);
      ass += `Dialogue: 0,${sTs},${eTs},CWI_Default,SFX,0,0,${marginVPx},,{\\i1\\b500\\1c&H00EDEAE8&}${ev.label}{\\i0}\n`;
    }

    if (!spec.words || spec.words.length === 0) continue;

    const firstOnsetMs = spec.words[0].start_ms;
    const lastOffsetMs = spec.words[spec.words.length - 1].end_ms + 350;
    const lineStartMs = Math.max(0, firstOnsetMs - (spec.presentation_offset_ms || 1750));

    const sLineTs = msToAssTimestamp(lineStartMs);
    const eLineTs = msToAssTimestamp(lastOffsetMs);

    const tokensAss: string[] = [];
    let cursorMs = lineStartMs;

    for (const w of spec.words) {
      const gapCs = Math.max(0, Math.floor((w.start_ms - cursorMs) / 10));
      const durCs = Math.max(1, Math.floor(w.duration_ms / 10));
      const spkBgr = hexToAssBgr(w.speaker.color_hex, '00');

      const t1Ms = Math.max(0, w.start_ms - lineStartMs);
      const tPeakMs = t1Ms + Math.max(20, Math.round(w.duration_ms * 0.18));
      const tSustainMs = t1Ms + Math.max(40, Math.round(w.duration_ms * 0.38));

      const peakPct = Math.round(100.0 * w.typography.pop_scale * w.typography.crest_scale);
      const sustainPct = Math.round(100.0 * w.typography.crest_sustain_scale);
      const wght = w.typography.wght;

      const holdWait = gapCs > 0 ? `\\k${gapCs}` : '';
      const override =
        `{${holdWait}\\1c${spkBgr}\\2c${readAheadAss}\\b${wght}` +
        `\\t(${t1Ms},${tPeakMs},\\fscx${peakPct}\\fscy${peakPct})` +
        `\\t(${tPeakMs},${tSustainMs},\\fscx${sustainPct}\\fscy${sustainPct})` +
        `\\kf${durCs}}${w.text}`;

      tokensAss.push(override);
      cursorMs = w.end_ms;
    }

    const joinedText = tokensAss.join(' ');
    ass += `Dialogue: 0,${sLineTs},${eLineTs},CWI_Default,${spec.words[0].speaker.id},0,0,${marginVPx},,${joinedText}\n`;
  }

  return ass;
}

export const ControlPanel: React.FC<ControlPanelProps> = ({
  intensity,
  onIntensityChange,
  selectedProfile,
  onProfileSelect,
  isLiveMode,
  onLiveModeToggle,
  presentationOffsetMs,
  onPresentationOffsetChange,
  captionSpecs,
  onLoadSampleData,
  onLoadDuneDemo,
  onLoadVideoFile,
  onLoadCaptionFile,
}) => {
  const handleExportAss = () => {
    if (captionSpecs.length === 0) {
      alert('No CaptionSpec data loaded to export.');
      return;
    }
    const assContent = compileAssClient(captionSpecs);
    const blob = new Blob([assContent], { type: 'text/plain;charset=utf-8' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = `cwi_captions_${Date.now()}.ass`;
    a.click();
    URL.revokeObjectURL(url);
  };

  const handleVideoUpload = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (file) onLoadVideoFile(file);
  };

  const handleCaptionUpload = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (file) onLoadCaptionFile(file);
  };

  return (
    <div
      style={{
        width: '100%',
        maxWidth: '1280px',
        backgroundColor: '#16181c',
        borderRadius: '12px',
        padding: '20px 24px',
        color: '#e7e9ea',
        display: 'flex',
        flexDirection: 'column',
        gap: '20px',
        boxSizing: 'border-box',
        border: '1px solid #2f3336',
      }}
    >
      {/* Top Bar: Mode Switch & Data Buttons */}
      <div
        style={{
          display: 'flex',
          flexWrap: 'wrap',
          alignItems: 'center',
          justifyContent: 'space-between',
          gap: '12px',
        }}
      >
        <div style={{ display: 'flex', alignItems: 'center', gap: '8px' }}>
          <button
            onClick={() => onLiveModeToggle(false)}
            style={{
              padding: '8px 16px',
              borderRadius: '20px',
              border: 'none',
              backgroundColor: !isLiveMode ? '#1d9bf0' : '#272c30',
              color: '#fff',
              fontWeight: 600,
              cursor: 'pointer',
              transition: 'all 0.2s',
            }}
          >
            🎬 VOD Studio
          </button>
          <button
            onClick={() => onLiveModeToggle(true)}
            style={{
              padding: '8px 16px',
              borderRadius: '20px',
              border: 'none',
              backgroundColor: isLiveMode ? '#00ba7c' : '#272c30',
              color: '#fff',
              fontWeight: 600,
              cursor: 'pointer',
              transition: 'all 0.2s',
            }}
          >
            🎙️ Live Stream
          </button>
        </div>

        <div style={{ display: 'flex', alignItems: 'center', gap: '10px' }}>
          {onLoadDuneDemo && (
            <button
              onClick={onLoadDuneDemo}
              title="Loads D:\dune\final_video.mp4 with 1,323 CWI expressive caption segments"
              style={{
                padding: '8px 16px',
                borderRadius: '8px',
                border: '1px solid #eab308',
                backgroundColor: 'rgba(234, 179, 8, 0.20)',
                color: '#facc15',
                cursor: 'pointer',
                fontWeight: 700,
                fontSize: '0.85rem',
                display: 'flex',
                alignItems: 'center',
                gap: '6px',
              }}
            >
              🏜️ Load Dune Demo
            </button>
          )}

          <button
            onClick={onLoadSampleData}
            style={{
              padding: '8px 14px',
              borderRadius: '8px',
              border: '1px solid #536471',
              backgroundColor: 'transparent',
              color: '#eff3f4',
              cursor: 'pointer',
              fontSize: '0.85rem',
            }}
          >
            ✨ Load Demo Data
          </button>

          <label
            style={{
              padding: '8px 14px',
              borderRadius: '8px',
              border: '1px solid #536471',
              backgroundColor: 'transparent',
              color: '#eff3f4',
              cursor: 'pointer',
              fontSize: '0.85rem',
            }}
          >
            📹 Open Video
            <input type="file" accept="video/*" onChange={handleVideoUpload} style={{ display: 'none' }} />
          </label>

          <label
            style={{
              padding: '8px 14px',
              borderRadius: '8px',
              border: '1px solid #536471',
              backgroundColor: 'transparent',
              color: '#eff3f4',
              cursor: 'pointer',
              fontSize: '0.85rem',
            }}
          >
            📄 Open .cwi.json
            <input type="file" accept=".json" onChange={handleCaptionUpload} style={{ display: 'none' }} />
          </label>

          <button
            onClick={handleExportAss}
            style={{
              padding: '8px 16px',
              borderRadius: '8px',
              border: 'none',
              backgroundColor: '#f59e0b',
              color: '#000',
              fontWeight: 700,
              cursor: 'pointer',
              fontSize: '0.85rem',
            }}
          >
            💾 Export .ass
          </button>
        </div>
      </div>

      {/* Middle Row: Intensity Slider & Read-Ahead Offset */}
      <div
        style={{
          display: 'grid',
          gridTemplateColumns: 'repeat(auto-fit, minmax(280px, 1fr))',
          gap: '20px',
          alignItems: 'center',
          backgroundColor: '#0f1115',
          padding: '16px 20px',
          borderRadius: '8px',
        }}
      >
        {/* Kinetic Intensity Slider */}
        <div style={{ display: 'flex', flexDirection: 'column', gap: '6px' }}>
          <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: '0.9rem', fontWeight: 600 }}>
            <span>Kinetic Animation Intensity</span>
            <span style={{ color: '#1d9bf0' }}>{Math.round(intensity * 100)}%</span>
          </div>
          <input
            type="range"
            min="0"
            max="100"
            value={Math.round(intensity * 100)}
            onChange={(e) => onIntensityChange(Number(e.target.value) / 100)}
            style={{ accentColor: '#1d9bf0', cursor: 'pointer' }}
          />
          <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: '0.75rem', color: '#71767b' }}>
            <span>0% (Static Subtitles)</span>
            <span>100% (Full 5 Channels)</span>
          </div>
        </div>

        {/* Read-Ahead Delay Floor */}
        <div style={{ display: 'flex', flexDirection: 'column', gap: '6px' }}>
          <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: '0.9rem', fontWeight: 600 }}>
            <span>Dual-Clock Read-Ahead Offset</span>
            <span style={{ color: '#00ba7c' }}>{presentationOffsetMs} ms</span>
          </div>
          <input
            type="range"
            min="420"
            max="3000"
            step="50"
            value={presentationOffsetMs}
            onChange={(e) => onPresentationOffsetChange(Number(e.target.value))}
            style={{ accentColor: '#00ba7c', cursor: 'pointer' }}
          />
          <div style={{ display: 'flex', justifyContent: 'space-between', fontSize: '0.75rem', color: '#71767b' }}>
            <span>420 ms (Min Floor)</span>
            <span>1750 ms (Default)</span>
            <span>3000 ms</span>
          </div>
        </div>
      </div>

      {/* Bottom Row: Profile Selector Cards */}
      <div>
        <div style={{ fontSize: '0.9rem', fontWeight: 600, marginBottom: '10px' }}>Customization Profiles</div>
        <div
          style={{
            display: 'grid',
            gridTemplateColumns: 'repeat(auto-fit, minmax(220px, 1fr))',
            gap: '12px',
          }}
        >
          {(Object.keys(PROFILES) as ProfileName[]).map((pKey) => {
            const p = PROFILES[pKey];
            const isSelected = selectedProfile === pKey;
            return (
              <div
                key={pKey}
                onClick={() => onProfileSelect(pKey)}
                style={{
                  padding: '12px 14px',
                  borderRadius: '8px',
                  border: isSelected ? '2px solid #1d9bf0' : '1px solid #2f3336',
                  backgroundColor: isSelected ? 'rgba(29, 155, 240, 0.1)' : '#1e2124',
                  cursor: 'pointer',
                  transition: 'all 0.15s ease-in-out',
                }}
              >
                <div style={{ fontWeight: 600, fontSize: '0.9rem', color: isSelected ? '#1d9bf0' : '#eff3f4' }}>
                  {p.label}
                </div>
                <div style={{ fontSize: '0.75rem', color: '#71767b', marginTop: '4px', lineHeight: '1.3' }}>
                  {p.description}
                </div>
              </div>
            );
          })}
        </div>
      </div>
    </div>
  );
};
