"""
ASS Compiler: Deterministic translation of CaptionSpec v2.0-cwi into Advanced SubStation Alpha (.ass)
Reference: docs/07_client_and_rendering/ffmpeg_ass_burnin.md (Section 2)
"""

from typing import List

try:
    from backend.schemas.caption_spec import CaptionSpec, WordToken
except ImportError:
    from typing import Any
    CaptionSpec = Any  # type: ignore
    WordToken = Any    # type: ignore


def hex_rgb_to_ass_bgr(hex_color: str, alpha_hex: str = "00") -> str:
    """Converts '#RRGGBB' to ASS '&HAABBGGRR&' format."""
    clean = hex_color.lstrip("#")
    if len(clean) != 6:
        return f"&H{alpha_hex}F7C34F&"
    r, g, b = clean[0:2], clean[2:4], clean[4:6]
    return f"&H{alpha_hex}{b.upper()}{g.upper()}{r.upper()}&"


def ms_to_ass_timestamp(ms: int) -> str:
    """Formats milliseconds as H:MM:SS.cc (centiseconds)."""
    ms = max(0, int(ms))
    total_cs = ms // 10
    cs = total_cs % 100
    total_sec = total_cs // 100
    s = total_sec % 60
    total_min = total_sec // 60
    m = total_min % 60
    h = total_min // 60
    return f"{h}:{m:02d}:{s:02d}.{cs:02d}"


def compile_captionspec_to_ass(
    specs: List[CaptionSpec],
    video_width: int = 1920,
    video_height: int = 1080,
) -> str:
    """
    Deterministically compiles CaptionSpec v2.0-cwi segments into an
    Advanced SubStation Alpha (.ass) script enforcing:
    - Lower 20% work area (MarginV within bottom 20% of video_height)
    - 90% opacity black box (&H1A000000&, where 0x1A = 26 = 10% transparency / 90% opacity)
    - -1.75s Read-Ahead neutral grey pre-display
    - \\kf karaoke Colour Turn, 1.15x Pop, Crest 0.70 sustain, and numeric \\b<wght>.
    """
    baseline_font_px = int(round(video_height * 0.05))  # 5% of screen height = 1.0x baseline
    margin_v_px = int(round(video_height * 0.06))       # Inside lower 20% work area
    read_ahead_ass = hex_rgb_to_ass_bgr("#B0B5BC", "00")

    header = f"""[Script Info]
; Script generated by Automated Caption with Intention (CwiRenderer v2.0-cwi)
Title: Caption with Intention Expressive Subtitles
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: {video_width}
PlayResY: {video_height}

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: CWI_Default,Roboto Flex,{baseline_font_px},&H00F7C34F&,{read_ahead_ass},&H1A000000&,&H1A000000&,400,0,0,0,100,100,0,0,3,16,0,2,80,80,{margin_v_px},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    event_lines: List[str] = []

    for spec in specs:
        # Render non-speech events (<|BGM|>, <|Applause|>, [laughter], [sighs])
        for ev in spec.non_speech_events:
            s_ts = ms_to_ass_timestamp(ev.start_ms)
            e_ts = ms_to_ass_timestamp(ev.end_ms)
            event_lines.append(
                f"Dialogue: 0,{s_ts},{e_ts},CWI_Default,SFX,0,0,{margin_v_px},,{{\\i1\\b500\\1c&H00EDEAE8&}}{ev.label}{{\\i0}}"
            )

        if not spec.words:
            continue

        # Line appears in read-ahead layer up to 1750ms before first word onset
        first_onset_ms = spec.words[0].start_ms
        last_offset_ms = spec.words[-1].end_ms + 350
        offset_ms = getattr(spec, "presentation_offset_ms", 1750) or 1750
        line_start_ms = max(0, first_onset_ms - offset_ms)

        s_line_ts = ms_to_ass_timestamp(line_start_ms)
        e_line_ts = ms_to_ass_timestamp(last_offset_ms)

        tokens_ass: List[str] = []
        cursor_ms = line_start_ms

        for w in spec.words:
            gap_cs = max(0, (w.start_ms - cursor_ms) // 10)
            dur_cs = max(1, w.duration_ms // 10)
            spk_bgr = hex_rgb_to_ass_bgr(w.speaker.color_hex, "00")

            t1_ms = max(0, w.start_ms - line_start_ms)
            t_peak_ms = t1_ms + max(20, int(round(w.duration_ms * 0.18)))
            t_sustain_ms = t1_ms + max(40, int(round(w.duration_ms * 0.38)))

            peak_pct = int(round(100.0 * w.typography.pop_scale * w.typography.crest_scale))
            sustain_pct = int(round(100.0 * w.typography.crest_sustain_scale))
            wght = w.typography.wght

            hold_wait = f"\\k{gap_cs}" if gap_cs > 0 else ""
            override = (
                f"{{{hold_wait}\\1c{spk_bgr}\\2c{read_ahead_ass}\\b{wght}"
                f"\\t({t1_ms},{t_peak_ms},\\fscx{peak_pct}\\fscy{peak_pct})"
                f"\\t({t_peak_ms},{t_sustain_ms},\\fscx{sustain_pct}\\fscy{sustain_pct})"
                f"\\kf{dur_cs}}}{w.text}"
            )
            tokens_ass.append(override)
            cursor_ms = w.end_ms

        joined_text = " ".join(tokens_ass)
        event_lines.append(
            f"Dialogue: 0,{s_line_ts},{e_line_ts},CWI_Default,{spec.words[0].speaker.id},0,0,{margin_v_px},,{joined_text}"
        )

    return header + "\n".join(event_lines) + "\n"
